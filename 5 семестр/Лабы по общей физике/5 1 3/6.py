# === ОПРЕДЕЛЕНИЕ I_0 ===
# I_0 - ток катода, берем как максимальный ток (минимальное рассеяние)
I0_1 = np.max(I1[I1 > 0])  # Для первого набора
I0_2 = np.max(I2[I2 > 0])  # Для второго набора

print(f"I_0 для накала 2.755 В: {I0_1:.3f} мкА")
print(f"I_0 для накала 2.925 В: {I0_2:.3f} мкА")

# === РАСЧЕТ ВЕРОЯТНОСТИ РАССЕЯНИЯ ===
# w(V) = -(1/C) * ln(I_a(V) / I_0)
# Поскольку C - константа, строим w(V) * C = -ln(I_a(V) / I_0)

# Фильтруем только положительные токи
mask1 = I1 > 0.001  # Избегаем деления на очень малые числа
mask2 = I2 > 0.001

V1_pos = V1[mask1]
I1_pos = I1[mask1]
w1 = -np.log(I1_pos / I0_1)

V2_pos = V2[mask2]
I2_pos = I2[mask2]
w2 = -np.log(I2_pos / I0_2)

# === ПОСТРОЕНИЕ ГРАФИКА ===
plt.figure(figsize=(10, 6))

plt.scatter(V1_pos, w1, color='blue', s=20, alpha=0.7, label='Накал 2.755 В', zorder=5)
plt.scatter(V2_pos, w2, color='red', s=20, alpha=0.7, label='Накал 2.925 В', zorder=5)

# Соединяем точки линиями для наглядности
plt.plot(V1_pos, w1, '-', color='blue', linewidth=1, alpha=0.5)
plt.plot(V2_pos, w2, '-', color='red', linewidth=1, alpha=0.5)

plt.xlabel('Энергия электронов $E = eV$, эВ', fontsize=13)
plt.ylabel('Вероятность рассеяния $w(V) \cdot C$', fontsize=13)
# plt.title('Зависимость вероятности рассеяния электронов от энергии', fontsize=14)
plt.legend(fontsize=11)
plt.grid(True, alpha=0.4)
plt.xlim(0, 12)
plt.ylim(-0.5, 3)

# Отмечаем характерные точки
plt.axvline(4.35, color='green', linestyle='--', alpha=0.5, linewidth=1.5, label='Первый максимум прохождения')
plt.axvline(10.35, color='orange', linestyle=':', alpha=0.5, linewidth=1.5, label='Первый минимум прохождения')
plt.legend(fontsize=10, loc='upper right')

plt.tight_layout()
plt.savefig('scattering_probability.png', dpi=300)
print("График сохранён как 'scattering_probability.png'")
plt.show()

# Вывод минимального значения вероятности (максимум прохождения)
min_w1_idx = np.argmin(w1)
min_w2_idx = np.argmin(w2)
print(f"\nМинимум вероятности рассеяния:")
print(f"Для накала 2.755 В: V = {V1_pos[min_w1_idx]:.2f} В, w*C = {w1[min_w1_idx]:.3f}")
print(f"Для накала 2.925 В: V = {V2_pos[min_w2_idx]:.2f} В, w*C = {w2[min_w2_idx]:.3f}")